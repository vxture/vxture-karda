function append(refs:number[],question:string,expectedAnswer:string|null,kind:DraftCase["kind"],split?:DraftCase["split"]){
  cases.push({
    id:"p"+String(cases.length+1).padStart(2,"0"),
    split:split ?? (refs.some(n=>n>40) ? "reserved" : "development"),
    kind,question,expectedAnswer,
    evidence:refs.map(n=>({sourceId:corpus.sources[0].id,sectionId:"reg-2015-art-"+n})),
  });
}
